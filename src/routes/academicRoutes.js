const router = require('express').Router();
const c = require('../controllers/academicController');
const { authenticate, allowRoles } = require('../middleware/auth');
router.use(authenticate);
router.get('/users', allowRoles('admin'), c.listUsers);
router.get('/users/:id', allowRoles('admin'), c.getUser);
router.post('/users', allowRoles('admin'), c.createUser);
router.patch('/users/:id', allowRoles('admin'), c.updateUser);
router.delete('/users/:id', allowRoles('admin'), c.deactivateUser);
router.get('/courses', c.listCourses);
router.post('/courses', allowRoles('admin'), c.createCourse);
router.get('/courses/:id', c.getCourse);
router.patch('/courses/:id', allowRoles('admin'), c.updateCourse);
router.delete('/courses/:id', allowRoles('admin'), c.deactivateCourse);
router.get('/sections', c.listSections);
router.post('/sections', allowRoles('admin'), c.createSection);
router.get('/sections/:id', c.getSection);
router.patch('/sections/:id', allowRoles('admin'), c.updateSection);
router.delete('/sections/:id', allowRoles('admin'), c.deactivateSection);
router.post('/enrollments', allowRoles('admin'), c.enrollStudent);
router.get('/enrollments', c.listEnrollments);
router.delete('/enrollments/:id', allowRoles('admin'), c.withdrawEnrollment);
router.get('/reports/enrollment-counts', allowRoles('admin'), c.getEnrollmentCounts);
module.exports = router;
